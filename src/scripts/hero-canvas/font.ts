export function getTextWidth(text: string, scale = 1, charSpacing = 1): number {
  if (text.length === 0) {
    return 0;
  }
  return text.length * 5 * scale + (text.length - 1) * charSpacing * scale;
}

export function textToCells(
  text: string,
  startCol: number,
  startRow: number,
  scale = 1,
  state: CellState = "filled",
  charSpacing = 1,
): TargetCell[] {
  const cells: TargetCell[] = [];
  let currentCol = startCol;

  for (const char of text) {
    const glyph = FONT_5X7[char] ?? FONT_5X7[char.toUpperCase()] ?? FONT_5X7[" "];
    if (glyph !== undefined) {
      for (let r = 0; r < 7; r++) {
        const rowStr = glyph[r] ?? "00000";
        for (let c = 0; c < 5; c++) {
          if (rowStr[c] === "1") {
            for (let sr = 0; sr < scale; sr++) {
              for (let sc = 0; sc < scale; sc++) {
                cells.push({
                  col: currentCol + c * scale + sc,
                  row: startRow + r * scale + sr,
                  state,
                  scale: 1,
                });
              }
            }
          }
        }
      }
    }
    currentCol += 5 * scale + charSpacing * scale;
  }

  return cells;
}

export function getMicroTextWidth(text: string, scale = 1, charSpacing = 1): number {
  if (text.length === 0) {
    return 0;
  }
  return text.length * 3 * scale + (text.length - 1) * charSpacing * scale;
}

export function microTextToCells(
  text: string,
  startCol: number,
  startRow: number,
  scale = 1,
  state: CellState = "filled",
  charSpacing = 1,
): TargetCell[] {
  const cells: TargetCell[] = [];
  const upper = text.toUpperCase();
  let currentCol = startCol;

  for (const char of upper) {
    const glyph = FONT_3X5[char] ?? FONT_3X5[" "];
    if (glyph !== undefined) {
      for (let r = 0; r < 5; r++) {
        const rowStr = glyph[r] ?? "000";
        for (let c = 0; c < 3; c++) {
          if (rowStr[c] === "1") {
            for (let sr = 0; sr < scale; sr++) {
              for (let sc = 0; sc < scale; sc++) {
                cells.push({
                  col: currentCol + c * scale + sc,
                  row: startRow + r * scale + sr,
                  state,
                  scale: 1,
                });
              }
            }
          }
        }
      }
    }
    currentCol += 3 * scale + charSpacing * scale;
  }

  return cells;
}
